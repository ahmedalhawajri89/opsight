test.describe('export, as an owner', () => {
  test.use({ storageState: authFile('owner') });

  /*
   * ONE download for the whole describe, deliberately.
   *
   * Export is rate-limited to ten per hour per user, because bulk extraction
   * is the exfiltration vector in this system (SECURITY.md §7). A suite that
   * spends two of those ten every run can be run five times an hour before it
   * starts failing against a safeguard that is working correctly — which is
   * the same mistake the Phase 03 suite made with the login limiter, in a new
   * costume. The limit is right; downloading the same file twice to make two
   * assertions about it was the waste.
   */
  test('downloads the filtered view, named and redacted by the server', async ({ page }) => {
    await page.goto('/products?search=a');

    /*
     * Wait for real rows before clicking. The button is in the DOM from the
     * first paint, but its handler is not attached until React hydrates —
     * clicking in between does nothing at all, silently, and the test then
     * waits ten seconds for a download that was never started.
     */
    await expect(page.getByRole('row').nth(1)).toBeVisible();

    const [download] = await Promise.all([
      page.waitForEvent('download'),
      page.getByRole('button', { name: 'Export CSV' }).click(),
    ]);

    // The SERVER names the file, date stamp and all. Reading it back requires
    // Content-Disposition to be CORS-exposed, or the browser hides the header
    // from JavaScript and the client silently invents a name instead.
    expect(download.suggestedFilename()).toMatch(/^products-\d{4}-\d{2}-\d{2}\.csv$/);

    const stream = await download.createReadStream();
    const chunks = [];

    for await (const chunk of stream) chunks.push(chunk);

    const body = Buffer.concat(chunks).toString('utf8');
    const [header, ...rows] = body.trim().split('\n');

    // A cost column, because an Owner may see cost. The column set comes from
    // the same resource the screen uses, so redaction is inherited.
    expect(header).toContain('Cost');
    expect(rows.length).toBeGreaterThan(0);

    /*
     * "Export" means "export what I am looking at". The screen was filtered to
     * names containing "a", and the file has to agree — the server runs the
     * list and the export through one query definition, and this asserts the
     * UI actually hands its live filters over.
     */
    const listed = await page.getByRole('row').nth(1).innerText();
    const firstName = listed.split('\t')[1] ?? '';

    if (firstName.trim() !== '') {
      expect(body).toContain(firstName.trim());
    }
  });
});

