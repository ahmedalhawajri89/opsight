import { expect, test } from '@playwright/test';

import { authFile } from './support/authState';

/**
 * The Phase 05 surfaces, through a real browser against a real backend.
 *
 * These cover what only an end-to-end test can: that the audit trail actually
 * records what the browser just did, that the export leaves the server with the
 * right columns in it, and that the last-Owner guard reaches the screen as a
 * sentence the user can act on rather than a generic failure.
 */

test.describe('the activity log, as an owner', () => {
  test.use({ storageState: authFile('owner') });

  test('shows real entries with an actor and an action', async ({ page }) => {
    await page.goto('/activity');

    await expect(page.getByRole('heading', { name: 'Activity log' })).toBeVisible();

    // The seeded history is written with auditing paused — a fabricated past
    // must not claim to be a record of user actions — so the entries here are
    // the ones this suite has generated by signing in.
    const table = page.getByRole('table');
    await expect(table).toBeVisible();

    // Scoped to the table: the action filter above it holds an
    // <option>auth.login</option> that an unscoped text match finds first, and
    // an <option> is never "visible".
    await expect(table.getByText('login').first()).toBeVisible();
  });

  test('records the sign-ins this suite performed', async ({ page }) => {
    await page.goto('/activity?action=auth.login');

    await expect(page.getByRole('row').nth(1)).toBeVisible();
  });

  test('pages by cursor, offering no page numbers', async ({ page }) => {
    await page.goto('/activity');

    /*
     * The absence is the assertion. Offset paging over the highest-growth
     * table gets slower as it fills, and shifts entries between pages while a
     * reader is working through them — an audit tool that can skip an entry
     * is not an audit tool.
     */
    await expect(page.getByRole('button', { name: 'Older' })).toBeVisible();
    await expect(page.getByText(/page \d+ of \d+/i)).toHaveCount(0);
  });

  test('states that it cannot be edited', async ({ page }) => {
    await page.goto('/activity');

    await expect(page.getByText(/append-only/i)).toBeVisible();
  });
});

test.describe('the activity log, as staff', () => {
  test.use({ storageState: authFile('staff') });

  test('is not in the navigation and is refused by direct URL', async ({ page }) => {
    await page.goto('/dashboard');

    const nav = page.getByRole('navigation', { name: 'Main' });
    await expect(nav.getByRole('link', { name: 'Activity log' })).toHaveCount(0);

    /*
     * Wait for the SERVER's refusal before asserting the screen. The dev API
     * (`php artisan serve`) handles one request at a time, so in a full run
     * this request can queue behind an export or a dashboard for longer than
     * the assertion timeout — the test was measuring the queue, not the page.
     */
    const refused = page.waitForResponse(
      (response) =>
        new URL(response.url()).pathname === '/api/v1/activity' && response.status() === 403,
    );

    await page.goto('/activity');
    await refused;

    await expect(page.getByText(/not available for your role/i).first()).toBeVisible();
  });
});

