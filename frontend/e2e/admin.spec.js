test.describe('settings', () => {
  test.use({ storageState: authFile('owner') });

  test('warns that two fields move historical figures', async ({ page }) => {
    await page.goto('/settings');

    await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible();

    // Stated before the change, on the fieldset itself.
    await expect(page.getByText(/moves which month, quarter or year/i)).toBeVisible();
  });

  test('raises a specific warning once such a field is actually changed', async ({ page }) => {
    await page.goto('/settings');

    await page.getByLabel('Fiscal year starts').selectOption('7');

    await expect(
      page.getByText(/change the totals reported for periods that have already/i),
    ).toBeVisible();

    // Not saved: this database is shared with the metric assertions in the
    // other specs, and a July fiscal year would move every YTD figure.
  });
});

test.describe('settings, as staff', () => {
  test.use({ storageState: authFile('staff') });

  test('are not reachable at all', async ({ page }) => {
    /*
     * Default deny. The read was briefly open to every role on the grounds
     * that currency and timezone are formatting inputs rather than secrets —
     * but the screens that format money already receive both in the meta of
     * the analytics responses they make anyway, so nothing outside this
     * screen needed the endpoint and the exception was not paying for itself.
     */
    await page.goto('/dashboard');

    const nav = page.getByRole('navigation', { name: 'Main' });
    await expect(nav.getByRole('link', { name: 'Settings' })).toHaveCount(0);

    await page.goto('/settings');
    await expect(page.getByText(/not available for your role/i).first()).toBeVisible();
  });
});
