test.describe('users, as an owner', () => {
  test.use({ storageState: authFile('owner') });

  test('lists the seeded accounts with their roles', async ({ page }) => {
    await page.goto('/settings/users');

    await expect(page.getByRole('heading', { name: 'Users' })).toBeVisible();
    // Cells, not text: the signed-in owner's own address is also in the header.
    await expect(page.getByRole('cell', { name: 'owner@opsight.test' })).toBeVisible();
    await expect(page.getByRole('cell', { name: 'staff@opsight.test' })).toBeVisible();
  });

  test('refuses to demote the last Owner, and says what to do instead', async ({ page }) => {
    await page.goto('/settings/users');

    const row = page.getByRole('row').filter({ hasText: 'owner@opsight.test' });

    await row.getByRole('combobox').selectOption('manager');

    /*
     * The guard is an availability guarantee, not a permission: Owner is the
     * only role that can promote anyone or change settings, so an
     * installation with no active Owner cannot be recovered through the
     * application at all. The message has to say how to get past it.
     */
    await expect(page.getByText(/last active Owner/i)).toBeVisible();
    await expect(page.getByText(/Promote another user/i)).toBeVisible();
  });

  test('explains that deactivation is not deletion before confirming', async ({ page }) => {
    await page.goto('/settings/users');

    const row = page.getByRole('row').filter({ hasText: 'analyst@opsight.test' });

    await row.getByRole('button', { name: 'Deactivate' }).click();

    await expect(page.getByRole('dialog')).toBeVisible();
    await expect(page.getByText(/lose access on their next request/i)).toBeVisible();
    await expect(page.getByText(/stays on record/i)).toBeVisible();

    // Left unconfirmed: this suite shares one database with the others, and
    // deactivating the analyst would break their sign-in elsewhere.
    await page.getByRole('button', { name: 'Cancel' }).click();
  });
});

test.describe('users, as a manager', () => {
  test.use({ storageState: authFile('manager') });

  test('cannot reach user administration', async ({ page }) => {
    // Manager holds full operational and financial authority and no authority
    // over access control — the one boundary a Manager does not cross.
    await page.goto('/settings/users');

    await expect(page.getByText(/not available for your role/i).first()).toBeVisible();
  });
});

